let locale: Locale = 'zh-CN';
try {
  if (typeof window !== 'undefined') {
    const preference = new URLSearchParams(window.location.search).get('lang') ?? localStorage.getItem('totu.locale');
    if (preference === 'en') locale = 'en';
    document.documentElement.lang = locale;
  }
} catch { /* 浏览器禁用存储时，仍使用默认中文。 */ }
const listeners = new Set<() => void>();
export const getLocale = (): Locale => locale;
export const isChinese = () => locale === 'zh-CN';
export function subscribeLocale(listener: () => void) {
  listeners.add(listener);
  return () => { listeners.delete(listener); };
}
export function setLocale(next: Locale) {
  locale = next;
  if (typeof window !== 'undefined') {
    document.documentElement.lang = next;
    try { localStorage.setItem('totu.locale', next); } catch { /* 存储不可用不影响本次切换。 */ }
    const url = new URL(window.location.href);
    url.searchParams.set('lang', next);
    window.history.replaceState(null, '', url);
  }
  listeners.forEach(listener => listener());
}
export function ui(key: string, params: Record<string, string | number> = {}): string {
  const template = isChinese() ? UI_STRING_TABLE[key] ?? key : ENGLISH_STRING_TABLE[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => String(params[name] ?? match));
}
export function cardStrings(card: { effectKey: string; name: string; benefits: string[] }): CardStrings {
  return isChinese() ? CARD_STRING_TABLE[card.effectKey] ?? card : card;
}
const CARD_KEYS_BY_NAME = new Map(allCards().map(card => [card.name, card.effectKey]));
export function cardName(name: string): string {
  const key = CARD_KEYS_BY_NAME.get(name);
  return isChinese() && key ? CARD_STRING_TABLE[key]?.name ?? name : name;
}

