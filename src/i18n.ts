export function choiceText(text: string): string {
  if (!isChinese()) return text;
  if (CHOICE_STRING_TABLE[text]) return CHOICE_STRING_TABLE[text];
  for (const [pattern, template] of CHOICE_PATTERNS) {
    const match = text.match(pattern);
    if (match) return template.replace(/\$(\d+)/g, (_, n: string) => match[Number(n)] ?? '');
  }
  return ui(text);
}
